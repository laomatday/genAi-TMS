-- Expand genAi TMS employee, request, notification and kiosk features.
alter table public.employees
  add column if not exists managed_locations text[] not null default '{}',
  add column if not exists direct_manager_id text null references public.employees(employee_id) on update cascade on delete set null,
  add column if not exists annual_leave_balance numeric(6,2) not null default 12,
  add column if not exists trusted_device_id text null,
  add column if not exists trusted_device_bound_at timestamptz null;
create index if not exists employees_direct_manager_idx on public.employees(direct_manager_id);

create table if not exists public.leave_requests (
  id uuid primary key default gen_random_uuid(),
  employee_id text not null references public.employees(employee_id) on update cascade on delete cascade,
  type text not null check (type in ('Nghỉ phép','Nghỉ ốm','Nghỉ không lương','Công tác','Làm việc tại nhà','WFH')),
  from_date date not null,
  to_date date not null,
  reason text not null default '',
  status text not null default 'Pending' check (status in ('Pending','Approved','Rejected')),
  manager_note text not null default '',
  approver_id text null references public.employees(employee_id) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint leave_requests_date_check check (to_date >= from_date)
);
create index if not exists leave_requests_employee_idx on public.leave_requests(employee_id, created_at desc);
create index if not exists leave_requests_status_idx on public.leave_requests(status, created_at desc);

create table if not exists public.attendance_explanations (
  id uuid primary key default gen_random_uuid(),
  employee_id text not null references public.employees(employee_id) on update cascade on delete cascade,
  attendance_date date not null,
  reason text not null,
  status text not null default 'Pending' check (status in ('Pending','Approved','Rejected')),
  manager_note text not null default '',
  approver_id text null references public.employees(employee_id) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(employee_id, attendance_date)
);
create index if not exists attendance_explanations_employee_idx on public.attendance_explanations(employee_id, created_at desc);
create index if not exists attendance_explanations_status_idx on public.attendance_explanations(status, created_at desc);

create table if not exists public.holidays (
  id bigint generated by default as identity primary key,
  name text not null,
  from_date date not null,
  to_date date not null,
  paid boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint holidays_date_check check (to_date >= from_date)
);
create index if not exists holidays_dates_idx on public.holidays(from_date, to_date);

create table if not exists public.kiosks (
  kiosk_id text primary key,
  name text not null,
  center_id text not null references public.locations(center_id) on update cascade on delete restrict,
  status text not null default 'Active' check (status in ('Active','Inactive')),
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists kiosks_center_idx on public.kiosks(center_id, status);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_employee_id text not null references public.employees(employee_id) on update cascade on delete cascade,
  title text not null,
  body text not null default '',
  type text not null default 'info' check (type in ('info','success','warning','error','request','explanation')),
  action_type text null,
  action_id uuid null,
  read_at timestamptz null,
  created_at timestamptz not null default now()
);
create index if not exists notifications_recipient_idx on public.notifications(recipient_employee_id, created_at desc);
create index if not exists notifications_unread_idx on public.notifications(recipient_employee_id, read_at) where read_at is null;

create or replace function tms_private.current_employee_id()
returns text language sql stable security definer set search_path = '' as $$
  select e.employee_id from public.employees e where e.auth_user_id = auth.uid() and e.status = 'Active' limit 1;
$$;
revoke all on function tms_private.current_employee_id() from public, anon;
grant usage on schema tms_private to authenticated;
grant execute on function tms_private.current_employee_id() to authenticated;

create or replace function tms_private.can_manage_employee(p_employee_id text)
returns boolean language sql stable security definer set search_path = '' as $$
  with actor as (
    select employee_id, role, managed_locations from public.employees where auth_user_id = auth.uid() and status = 'Active' limit 1
  ), target as (
    select employee_id, center_id, direct_manager_id from public.employees where employee_id = p_employee_id
  )
  select exists (
    select 1 from actor a cross join target t
    where a.role in ('Admin','HR')
       or (a.role in ('Director','Manager','Leader') and (t.direct_manager_id = a.employee_id or t.center_id = any(coalesce(a.managed_locations, '{}'::text[]))))
  );
$$;
revoke all on function tms_private.can_manage_employee(text) from public, anon;
grant execute on function tms_private.can_manage_employee(text) to authenticated;

