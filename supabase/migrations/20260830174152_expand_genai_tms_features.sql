create or replace function public.register_or_validate_trusted_device(p_device_id text)
returns table(ok boolean, bound boolean, message text)
language plpgsql security definer set search_path = '' as $$
declare v_employee public.employees%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_device_id is null or length(trim(p_device_id)) < 8 or length(p_device_id) > 160 then return query select false, false, 'Thiết bị không hợp lệ.'; return; end if;
  select * into v_employee from public.employees where auth_user_id = auth.uid() and status = 'Active' for update;
  if not found then return query select false, false, 'Không tìm thấy hồ sơ nhân viên đang hoạt động.'; return; end if;
  if v_employee.trusted_device_id is null or v_employee.trusted_device_id = '' then
    update public.employees set trusted_device_id = p_device_id, trusted_device_bound_at = now(), updated_at = now() where employee_id = v_employee.employee_id;
    return query select true, true, 'Đã đăng ký thiết bị tin cậy.';
  elsif v_employee.trusted_device_id = p_device_id then return query select true, false, 'Thiết bị đã được xác thực.';
  else return query select false, false, 'Tài khoản đã liên kết với thiết bị khác. Liên hệ quản trị viên để đặt lại thiết bị.';
  end if;
end; $$;
revoke all on function public.register_or_validate_trusted_device(text) from public, anon;
grant execute on function public.register_or_validate_trusted_device(text) to authenticated;

create or replace function public.review_leave_request(p_id uuid, p_status text, p_note text default '')
returns void language plpgsql security definer set search_path = '' as $$
declare v_request public.leave_requests%rowtype; v_actor text;
begin
  if p_status not in ('Approved','Rejected') then raise exception 'Invalid status'; end if;
  select * into v_request from public.leave_requests where id = p_id for update;
  if not found then raise exception 'Request not found'; end if;
  if not tms_private.can_manage_employee(v_request.employee_id) then raise exception 'Forbidden'; end if;
  select tms_private.current_employee_id() into v_actor;
  update public.leave_requests set status = p_status, manager_note = coalesce(p_note,''), approver_id = v_actor, updated_at = now() where id = p_id;
end; $$;
revoke all on function public.review_leave_request(uuid,text,text) from public, anon;
grant execute on function public.review_leave_request(uuid,text,text) to authenticated;

