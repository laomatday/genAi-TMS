create or replace function public.notify_tms_review_result()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_title text; v_type text;
begin
  if old.status = new.status or new.status = 'Pending' then return new; end if;
  v_type := case when tg_table_name = 'leave_requests' then 'request' else 'explanation' end;
  v_title := case when tg_table_name = 'leave_requests' then 'Yêu cầu đã được xử lý' else 'Giải trình đã được xử lý' end;
  insert into public.notifications(recipient_employee_id,title,body,type,action_type,action_id)
  values (new.employee_id, v_title, case when new.status = 'Approved' then 'Đã duyệt' else 'Đã từ chối' end || case when coalesce(new.manager_note,'') <> '' then ': ' || new.manager_note else '' end, v_type, v_type, new.id);
  return new;
end; $$;
revoke all on function public.notify_tms_review_result() from public, anon, authenticated;
drop trigger if exists leave_requests_notify_status on public.leave_requests;
create trigger leave_requests_notify_status after update of status on public.leave_requests for each row execute function public.notify_tms_review_result();
drop trigger if exists explanations_notify_status on public.attendance_explanations;
create trigger explanations_notify_status after update of status on public.attendance_explanations for each row execute function public.notify_tms_review_result();
